create table if not exists public.cylinders (
  id bigint generated by default as identity primary key,
  item_key text not null,
  type_name text not null,
  gas_balance numeric not null default 0 check (gas_balance >= 0),
  empty_count numeric not null default 0,
  full_count numeric not null default 0,
  transaction_date date,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cutting_discs (
  id bigint generated by default as identity primary key,
  type_name text not null,
  code text,
  received_by text,
  received_date date,
  scrapped_date date,
  source_sheet text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

